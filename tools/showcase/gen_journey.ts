  const owner = OWNER[q.code];
  out.push(`update public.quotes set created_by = '${ACC[owner]}', account_signed_by = '${ACC[owner]}' where code = '${q.code}' and id::text in (select row_id from public.seed_registry where table_name = 'quotes');`);
  const req = Date.parse(q.req);
  const sent = Date.parse(q.sent);
  const total = workingMsBetween(req, sent, cal);
  const ev: [string, number][] = [];
  if (q.band !== 'send_now') {
    let t = req;
    for (const [action, f] of PLAN[owner][q.band]) {
      t = addWorkingMs(t, Math.round(total * f), cal);
      ev.push([action, t]);
    }
    if (t >= sent) throw new Error(`${q.code}: plan overflows`);
  }
  // Account ký người lập: lúc gửi duyệt đầu tiên, hoặc lúc gửi thẳng cho khách.
  const accSigned = ev.find((e) => e[0] === 'quote.submitted')?.[1] ?? sent;
  ev.push(['quote.sent', sent]);
  out.push(`update public.quotes set account_signed_at = '${new Date(accSigned).toISOString()}'${ev.some((e) => e[0].endsWith('signed')) ? `, signed_at = '${new Date(ev.filter((e) => e[0].endsWith('signed')).pop()![1]).toISOString()}', signed_by = (select id from public.profiles where role = 'ceo' order by created_at limit 1)` : ''} where code = '${q.code}' and id::text in (select row_id from public.seed_registry where table_name = 'quotes');`);
