// Builds the GitHub Pages site (the content of the gh-pages branch):
//   /            Pilot web app   (served at https://<owner>.github.io/<repo>/)
//   /demo/       Demo web app    (served at https://<owner>.github.io/<repo>/demo/)
//   /edge/       Edge Function bundle, imported by the deployed function at a pinned commit
//   /404.html    sends deep links back to the right app root (GitHub Pages has no rewrites)
// Public values only: project URLs and publishable keys come from deploy/github-pages.json.
// Usage: node scripts/build-pages.mjs [outDir]   (default dist/pages)
import { execSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const cfg = JSON.parse(readFileSync(join(root, 'deploy', 'github-pages.json'), 'utf8'));
const out = join(root, process.argv[2] ?? join('dist', 'pages'));

function configJs(env) {
  const c = cfg[env];
  return (
    `// Go Media Ops Hub · ${env === 'demo' ? 'Demo' : 'Pilot'} · generated by scripts/build-pages.mjs\n` +
    `// Public values (data is protected by Row Level Security).\n` +
    `window.OPS_HUB_CONFIG = ${JSON.stringify({ supabaseUrl: c.supabaseUrl, supabaseAnonKey: c.publishableKey, environment: env }, null, 2)};\n`
  );
}

function build(base, dest, env) {
  execSync('npx vite build --logLevel warn', { cwd: root, stdio: 'inherit', env: { ...process.env, OPS_BASE: base } });
  mkdirSync(dirname(dest), { recursive: true });
  cpSync(join(root, 'dist', 'web'), dest, { recursive: true });
  writeFileSync(join(dest, 'config.js'), configJs(env));
  rmSync(join(dest, '_redirects'), { force: true }); // Netlify-only file
}

rmSync(out, { recursive: true, force: true });
const repoBase = `/${cfg.repo}/`;
const tmp = join(root, 'dist', 'pages-tmp');
rmSync(tmp, { recursive: true, force: true });
build(`${repoBase}demo/`, join(tmp, 'demo'), 'demo');
build(repoBase, out, 'pilot');
cpSync(join(tmp, 'demo'), join(out, 'demo'), { recursive: true });
rmSync(tmp, { recursive: true, force: true });
rmSync(join(out, 'demo', '404.html'), { force: true }); // only the site-root 404.html is used

// Edge Function bundle, named by domain version so each deployed version has its own file.
execSync('node scripts/build-function.mjs', { cwd: root, stdio: 'inherit' });
const bundle = readFileSync(join(root, 'dist', 'edge', 'ops-hub', 'index.ts'), 'utf8');
const version = /domain ([0-9a-f]{10})/.exec(bundle)?.[1];
if (!version) throw new Error('domain version not found in the function bundle');
mkdirSync(join(out, 'edge'), { recursive: true });
writeFileSync(join(out, 'edge', `ops-hub-${version}.ts`), bundle);

writeFileSync(join(out, '.nojekyll'), '');
writeFileSync(join(out, 'README.md'), `# gh-pages\n\nGenerated by \`scripts/build-pages.mjs\` from the main branch. Do not edit by hand.\n`);
if (!existsSync(join(out, 'index.html')) || !existsSync(join(out, 'demo', 'index.html'))) throw new Error('build incomplete');
console.log(`GitHub Pages site → ${out} (pilot ${repoBase}, demo ${repoBase}demo/, edge/ops-hub-${version}.ts)`);
